begin;

create table if not exists public.chat_rooms (
  id          bigint generated by default as identity primary key,
  name        text not null,
  kind        text not null default 'course' check (kind in ('general','course')),
  course_id   bigint references public.courses(id) on delete cascade,
  created_by  bigint references public.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  unique (kind, course_id)
);

create table if not exists public.chat_messages (
  id          bigint generated by default as identity primary key,
  room_id     bigint not null references public.chat_rooms(id) on delete cascade,
  user_id     bigint not null references public.users(id) on delete cascade,
  author_name text,
  body        text not null,
  created_at  timestamptz not null default now()
);

create index if not exists idx_chat_messages_room on public.chat_messages(room_id, id desc);

insert into public.chat_rooms (name, kind, course_id, created_by)
select 'الساحة العامة', 'general', null, 1
where not exists (select 1 from public.chat_rooms where kind = 'general');

insert into public.chat_rooms (name, kind, course_id, created_by)
select 'غرفة ' || code || ' — ' || title, 'course', id, teacher_id
from public.courses
where not exists (
  select 1 from public.chat_rooms cr where cr.kind = 'course' and cr.course_id = courses.id
);

-- RLS
alter table public.chat_rooms enable row level security;
alter table public.chat_messages enable row level security;

commit;
