-- ============================================================
-- 0100_auth_bridge.sql — جسر الهوية: ربط users الحالي بـ auth.users
-- ============================================================
-- إضافي بالكامل: لا يعدّل بيانات قائمة، ولا يحذف شيئاً.
--  1) users.auth_id (uuid) + قيد فريد + مفتاح خارجي إلى auth.users
--  2) جدول audit_logs + فهارسه
--  3) دوال الهوية المساعدة (security definer) المستخدمة لاحقاً في RLS/RPC
--
-- ملاحظة: هذا الترحيل لا يفعّل RLS على الجداول ولا يمنح authenticated أي
-- وصول. تطبيق Express يستمر بالعمل عبر service_role كما هو.
-- ============================================================

begin;

-- ---------------------------------------------------------------------------
-- 1) جسر الهوية
-- ---------------------------------------------------------------------------
alter table public.users
  add column if not exists auth_id uuid;

-- قيد فريد (auth_id) — يُسمح بتكرار NULL قبل الربط
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.users'::regclass
      and conname = 'users_auth_id_key'
  ) then
    alter table public.users
      add constraint users_auth_id_key unique (auth_id);
  end if;
end $$;

-- مفتاح خارجي إلى auth.users.
-- on delete set null (وليس cascade): حذف حساب Auth لا يجوز أن يمحو بيانات
-- الطالب وسجلاته الأكاديمية. يُترك الصف ويُعطَّل عبر is_active عند الحاجة.
alter table public.users
  drop constraint if exists users_auth_id_fkey;

alter table public.users
  add constraint users_auth_id_fkey
  foreign key (auth_id) references auth.users(id) on delete set null;

create index if not exists idx_users_auth_id
  on public.users (auth_id);

-- البحث بالرمز عند إنشاء/ربط الحسابات
create index if not exists idx_users_platform_id
  on public.users (platform_id);

-- ---------------------------------------------------------------------------
-- 2) سجل العمليات الحساسة
-- ---------------------------------------------------------------------------
create table if not exists public.audit_logs (
  id          bigint generated by default as identity primary key,
  actor_id    bigint references public.users(id) on delete set null,
  action      text not null,
  table_name  text,
  record_id   bigint,
  old_data    jsonb,
  new_data    jsonb,
  created_at  timestamptz not null default now()
);

create index if not exists idx_audit_logs_created_at
  on public.audit_logs (created_at desc);

create index if not exists idx_audit_logs_actor
  on public.audit_logs (actor_id, created_at desc);

create index if not exists idx_audit_logs_record
  on public.audit_logs (table_name, record_id);

-- بلا سياسات RLS: الوصول عبر service_role أو دوال security definer فقط.
alter table public.audit_logs enable row level security;
revoke all on public.audit_logs from public, anon, authenticated;
grant all on public.audit_logs to service_role;

do $$
begin
  if exists (
    select 1 from pg_class
    where oid = to_regclass('public.audit_logs_id_seq') and relkind = 'S'
  ) then
    execute 'grant usage, select on sequence public.audit_logs_id_seq to service_role';
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- 3) دوال الهوية المساعدة
-- ---------------------------------------------------------------------------
-- كل الدوال: security definer + search_path ثابت + سحب التنفيذ من public/anon.
-- auth.uid() يُرجع uuid حساب Supabase، ونحوّله إلى users.id (bigint).

create or replace function public.current_user_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select u.id
  from public.users u
  where u.auth_id = auth.uid()
    and u.is_active = true
  limit 1;
$$;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select u.role
  from public.users u
  where u.auth_id = auth.uid()
    and u.is_active = true
  limit 1;
$$;

create or replace function public.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.users u
    where u.auth_id = auth.uid()
      and u.is_active = true
  );
$$;

-- المالك = أول أستاذ في الجدول (نفس تعريف founderId في التطبيق الحالي)
create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    public.current_user_id() = (
      select min(u.id) from public.users u where u.role = 'teacher'
    ),
    false
  );
$$;

create or replace function public.is_teacher()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_role() = 'teacher';
$$;

create or replace function public.is_assistant()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_role() = 'assistant';
$$;

create or replace function public.is_student()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_role() = 'student';
$$;

-- أستاذ المقرر (أو المالك)
create or replace function public.teaches_course(p_course bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.courses c
    where c.id = p_course
      and c.teacher_id = public.current_user_id()
  ) or public.is_owner();
$$;

-- طالب مسجّل ونشط في المقرر
create or replace function public.is_enrolled(p_course bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.enrollments e
    where e.course_id = p_course
      and e.student_id = public.current_user_id()
      and e.status = 'active'
  );
$$;

-- المستخدم الحالي هو صاحب المعرف (أو المالك)
create or replace function public.is_self_or_owner(p_user bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_id() = p_user or public.is_owner();
$$;

-- ---------------------------------------------------------------------------
-- 4) المنح: لا تنفيذ لأي دالة من public/anon
-- ---------------------------------------------------------------------------
revoke all on function public.current_user_id() from public, anon, authenticated;
revoke all on function public.current_user_role() from public, anon, authenticated;
revoke all on function public.is_active_user() from public, anon, authenticated;
revoke all on function public.is_owner() from public, anon, authenticated;
revoke all on function public.is_teacher() from public, anon, authenticated;
revoke all on function public.is_assistant() from public, anon, authenticated;
revoke all on function public.is_student() from public, anon, authenticated;
revoke all on function public.teaches_course(bigint) from public, anon, authenticated;
revoke all on function public.is_enrolled(bigint) from public, anon, authenticated;
revoke all on function public.is_self_or_owner(bigint) from public, anon, authenticated;

grant execute on function public.current_user_id() to authenticated, service_role;
grant execute on function public.current_user_role() to authenticated, service_role;
grant execute on function public.is_active_user() to authenticated, service_role;
grant execute on function public.is_owner() to authenticated, service_role;
grant execute on function public.is_teacher() to authenticated, service_role;
grant execute on function public.is_assistant() to authenticated, service_role;
grant execute on function public.is_student() to authenticated, service_role;
grant execute on function public.teaches_course(bigint) to authenticated, service_role;
grant execute on function public.is_enrolled(bigint) to authenticated, service_role;
grant execute on function public.is_self_or_owner(bigint) to authenticated, service_role;

notify pgrst, 'reload schema';

commit;
