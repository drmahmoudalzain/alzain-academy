begin;

-- البحوث (طلبات نشر)
create table if not exists public.publications (
  id                 bigint generated by default as identity primary key,
  author_id          bigint not null references public.users(id) on delete restrict,
  title              text not null,
  abstract_ar        text,
  abstract_en        text,
  keywords           text,
  manuscript_file    text,
  status             text not null default 'submitted'
                     check (status in ('submitted','screening','under_review','revisions','accepted','published','rejected')),
  editor_note        text,
  decision_note      text,
  assigned_reviewers bigint[] default '{}',
  published_at       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create table if not exists public.publication_reviews (
  id              bigint generated by default as identity primary key,
  publication_id  bigint not null references public.publications(id) on delete cascade,
  reviewer_id     bigint not null references public.users(id) on delete cascade,
  score_authenticity numeric(4,2),     -- الأصالة والإضافة (10)
  score_methodology  numeric(4,2),     -- الإشكالية والمنهجية (10)
  score_citation     numeric(4,2),     -- التوثيق والدقة (10)
  score_analysis     numeric(4,2),     -- التحليل والتطبيق (10)
  score_clarity      numeric(4,2),     -- الصياغة والتنظيم (10)
  total_score     numeric(5,2),
  verdict         text check (verdict in ('accept','minor','major','reject')),
  comments        text,
  created_at      timestamptz not null default now(),
  unique (publication_id, reviewer_id)
);

create index if not exists idx_publications_status on public.publications(status, id desc);
create index if not exists idx_reviews_pub on public.publication_reviews(publication_id);

alter table public.publications enable row level security;
alter table public.publication_reviews enable row level security;

commit;
