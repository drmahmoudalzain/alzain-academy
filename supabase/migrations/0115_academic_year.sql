alter table public.graduation_approvals enable row level security;
revoke all on public.graduation_approvals from public, anon, authenticated;
grant all on public.graduation_approvals to service_role;

do $$
declare f text;
begin
  foreach f in array array[
    'current_academic_year_id()',
    'current_semester_id(smallint)',
    'management_enroll_student(bigint,text)',
    'management_change_student_track(bigint,text,smallint,boolean)',
    'management_enroll_student_in_track(bigint,text,smallint)',
    'management_transfer_student(bigint,bigint,bigint)',
    'management_set_enrollment_status(bigint,bigint,text)',
    'management_remove_enrollment(bigint,bigint)'
  ] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;

grant execute on function public.current_academic_year_id() to service_role;
grant execute on function public.current_semester_id(smallint) to service_role;

notify pgrst, 'reload schema';

commit;
