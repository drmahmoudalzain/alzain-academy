select id, 2, 'open' from public.academic_years where code = 'CURRENT';

-- ---------------------------------------------------------------------------
-- 2) دوال الفترة الحالية — تُستخدم كقيم افتراضية ولتقييد الدوال القديمة
-- ---------------------------------------------------------------------------
create or replace function public.current_academic_year_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id
  from public.academic_years
  where status = 'open'
  order by id desc
  limit 1;
$$;

create or replace function public.current_semester_id(p_term smallint default 1)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select s.id
  from public.semesters s
  where s.year_id = public.current_academic_year_id()
    and s.term_no = p_term;
$$;

