-- ============================================================
-- 0115_academic_year.sql
-- العام الدراسي والفصلان لطلاب وطالبات البكالوريوس فقط.
--
-- المرحلة الأولى: البنية + backfill + استبدال مفتاح التسجيل.
-- تسجيلات اليوم تُصنَّف «العام الحالي / الفصل الأول».
-- لا نقل للدرجات ولا تغيير في صلاحية الأستاذ.
