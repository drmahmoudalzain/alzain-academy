create table public.academic_years (
  id          bigint generated by default as identity primary key,
  label       text not null,
  code        text not null unique,
  status      text not null default 'open' check (status in ('open', 'closed', 'archived')),
  starts_at   timestamptz not null default now(),
  closed_at   timestamptz,
  created_at  timestamptz not null default now(),
  check (closed_at is null or status in ('closed', 'archived'))
);

create table public.semesters (
  id        bigint generated by default as identity primary key,
  year_id   bigint not null references public.academic_years(id) on delete restrict,
  term_no   smallint not null check (term_no in (1, 2)),
  status    text not null default 'open' check (status in ('open', 'closed')),
  unique (year_id, term_no),
  unique (year_id, id)
);

insert into public.academic_years (label, code, status)
values ('العام الحالي', 'CURRENT', 'open');

