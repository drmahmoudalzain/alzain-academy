-- ============================================================
-- منصة آل الزين للعلوم القانونية والعدلية — المخطط الأولي
-- PostgreSQL / Supabase — مطابق للتقرير التقني (القسم 5)
-- ============================================================

begin;

-- ---------- 1) المستخدمون والجلسات ----------
create table if not exists public.users (
  id                  bigint generated by default as identity primary key,
  role                text not null check (role in ('teacher','student')),
  name                text not null,
  email               text unique,
  university_id       text unique,
  phone               text,
  password_hash       text,
  must_change_password boolean not null default false,
  is_active           boolean not null default true,
  track               text check (track in ('bachelor','equiv')) default 'bachelor',
  level               smallint check (level between 1 and 4),
  gender              text check (gender in ('M','F')),
  position            text,
  is_staff            boolean not null default false,
  created_at          timestamptz not null default now(),
  last_login          timestamptz
);

create table if not exists public.sessions (
  token_hash  text primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  expires_at  timestamptz not null,
  created_at  timestamptz not null default now()
);

-- ---------- 2) المقررات والتسجيل ----------
create table if not exists public.courses (
  id                 bigint generated by default as identity primary key,
  teacher_id         bigint not null references public.users(id) on delete restrict,
  title              text not null,
  code               text not null unique,
  description        text,
  color              text,
  attendance_weight  numeric(5,2) not null default 10,   -- 10%
  exams_weight       numeric(5,2) not null default 60,   -- 60%
  assignments_weight numeric(5,2) not null default 30,   -- 30%
  archived           boolean not null default false,
  track              text not null default 'bachelor' check (track in ('bachelor','equiv')),
  level              smallint check (level between 1 and 4),
  created_at         timestamptz not null default now()
);

create table if not exists public.enrollments (
  course_id  bigint not null references public.courses(id) on delete cascade,
  student_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (course_id, student_id)
);

-- ---------- 3) المحاضرات ونوعها ----------
create table if not exists public.lectures (
  id              bigint generated by default as identity primary key,
  course_id       bigint not null references public.courses(id) on delete cascade,
  title           text not null,
  description     text,
  youtube_url     text,
  live_url        text,
  scheduled_at    timestamptz,
  duration_min    integer not null default 120,
  attendance_code text,
  attendance_open boolean not null default false,
  lecture_type    text not null default 'direct' check (lecture_type in ('direct','online','recorded')),
  recording_note  text,
  status          text not null default 'scheduled',
  created_at      timestamptz not null default now()
);

create table if not exists public.files (
  id            bigint generated by default as identity primary key,
  course_id     bigint references public.courses(id) on delete cascade,
  lecture_id    bigint references public.lectures(id) on delete cascade,
  assignment_id bigint,
  uploader_id   bigint references public.users(id) on delete set null,
  filename      text not null,
  original_name text,
  mime          text,
  size          bigint,
  kind          text,
  created_at    timestamptz not null default now()
);

-- ---------- 4) الحضور والتتبع ----------
create table if not exists public.attendance (
  id         bigint generated by default as identity primary key,
  lecture_id bigint not null references public.lectures(id) on delete cascade,
  student_id bigint not null references public.users(id) on delete cascade,
  method     text,
  code_used  text,
  created_at timestamptz not null default now(),
  unique (lecture_id, student_id)
);

create table if not exists public.lecture_presence (
  lecture_id        bigint not null references public.lectures(id) on delete cascade,
  student_id        bigint not null references public.users(id) on delete cascade,
  total_seconds     integer not null default 0,
  last_heartbeat_at timestamptz,
  primary key (lecture_id, student_id)
);

-- ---------- 5) أسئلة المحاضرة التفاعلية ----------
create table if not exists public.questions (
  id              bigint generated by default as identity primary key,
  lecture_id      bigint not null references public.lectures(id) on delete cascade,
  text            text not null,
  type            text not null check (type in ('poll','mcq','multi','truefalse')),
  options         jsonb,
  correct_index   integer,
  correct_indices jsonb,
  is_open         boolean not null default true,
  created_at      timestamptz not null default now()
);

create table if not exists public.question_answers (
  id              bigint generated by default as identity primary key,
  question_id     bigint not null references public.questions(id) on delete cascade,
  student_id      bigint not null references public.users(id) on delete cascade,
  choice_index    integer,
  choice_indices  jsonb,
  text            text,
  created_at      timestamptz not null default now(),
  unique (question_id, student_id)
);

-- ---------- 6) الاختبارات ----------
create table if not exists public.exams (
  id          bigint generated by default as identity primary key,
  course_id   bigint not null references public.courses(id) on delete cascade,
  title       text not null,
  description text,
  starts_at   timestamptz,
  ends_at     timestamptz,
  duration_min integer,
  is_published boolean not null default false,
  exam_kind   text not null default 'exam' check (exam_kind in ('exam','assignment')),
  lecture_id  bigint references public.lectures(id) on delete set null,
  created_at  timestamptz not null default now()
);

create table if not exists public.exam_questions (
  id              bigint generated by default as identity primary key,
  exam_id         bigint not null references public.exams(id) on delete cascade,
  type            text not null check (type in ('mcq','multi','truefalse','essay')),
  text            text not null,
  options         jsonb,
  correct_index   integer,
  correct_indices jsonb,
  points          numeric(6,2) not null default 1,
  position        integer not null default 0
);

create table if not exists public.exam_attempts (
  id           bigint generated by default as identity primary key,
  exam_id      bigint not null references public.exams(id) on delete cascade,
  student_id   bigint not null references public.users(id) on delete cascade,
  started_at   timestamptz not null default now(),
  submitted_at timestamptz,
  score        numeric(6,2),
  status       text not null default 'in_progress',
  graded_at    timestamptz,
  unique (exam_id, student_id)
);

create table if not exists public.exam_answers (
  id              bigint generated by default as identity primary key,
  attempt_id      bigint not null references public.exam_attempts(id) on delete cascade,
  question_id     bigint not null references public.exam_questions(id) on delete cascade,
  choice_index    integer,
  choice_indices  jsonb,
  text            text,
  points          numeric(6,2),
  feedback        text,
  unique (attempt_id, question_id)
);

-- ---------- 7) الواجبات والتسليم ----------
create table if not exists public.assignments (
  id          bigint generated by default as identity primary key,
  course_id   bigint not null references public.courses(id) on delete cascade,
  title       text not null,
  description text,
  due_at      timestamptz,
  max_points  numeric(6,2) not null default 10,
  created_at  timestamptz not null default now()
);

create table if not exists public.submissions (
  id            bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id    bigint not null references public.users(id) on delete cascade,
  text          text,
  file_id       bigint references public.files(id) on delete set null,
  submitted_at  timestamptz not null default now(),
  points        numeric(6,2),
  feedback      text,
  graded_at     timestamptz,
  unique (assignment_id, student_id)
);

-- ---------- 8) الإشعارات ----------
create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  audience   text not null default 'all' check (audience in ('all','course','user')),
  course_id  bigint references public.courses(id) on delete cascade,
  user_id    bigint references public.users(id) on delete cascade,
  title      text not null,
  body       text,
  link       text,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.notification_reads (
  notification_id bigint not null references public.notifications(id) on delete cascade,
  user_id         bigint not null references public.users(id) on delete cascade,
  read_at         timestamptz not null default now(),
  primary key (notification_id, user_id)
);

-- ---------- 9) الإعدادات والذكاء الاصطناعي ----------
create table if not exists public.settings (
  key   text primary key,
  value text
);

create table if not exists public.ai_messages (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  role       text not null check (role in ('system','user','assistant')),
  content    text not null,
  created_at timestamptz not null default now()
);

-- ---------- 10) المكتبة والبحوث ----------
create table if not exists public.library_sections (
  id         bigint generated by default as identity primary key,
  name       text not null unique,
  icon       text,
  position   integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.library_items (
  id            bigint generated by default as identity primary key,
  section_id    bigint not null references public.library_sections(id) on delete cascade,
  title         text not null,
  description   text,
  filename      text,
  original_name text,
  mime          text,
  size          bigint,
  kind          text,
  created_by    bigint references public.users(id) on delete set null,
  researcher    text,
  journal       text,
  publish_year  integer,
  doi           text,
  abstract      text,
  created_at    timestamptz not null default now()
);

-- ---------- 11) النقاط (points ledger) ----------
create table if not exists public.points_ledger (
  id            bigint generated by default as identity primary key,
  user_id       bigint not null references public.users(id) on delete cascade,
  course_id     bigint not null references public.courses(id) on delete cascade,
  source_type   text not null check (source_type in ('attendance','interaction','assignment')),
  source_id     bigint,
  source_detail text,
  points        integer not null default 0,
  created_at    timestamptz not null default now(),
  unique (user_id, course_id, source_type, source_id)
);

-- ---------- 12) الأرشيف المؤقت (30 يوماً) ----------
create table if not exists public.archived_records (
  id          bigint generated by default as identity primary key,
  table_name  text not null,
  record_id   bigint,
  label       text,
  data        jsonb,
  archived_by bigint references public.users(id) on delete set null,
  archived_at timestamptz not null default now()
);

-- ---------- 13) خزنة كلمات المرور (للمالك فقط) ----------
create table if not exists public.credentials_vault (
  user_id       bigint primary key references public.users(id) on delete cascade,
  password_plain text,
  updated_at    timestamptz not null default now()
);

-- ---------- فهارس مساعدة ----------
create index if not exists idx_sessions_user        on public.sessions(user_id);
create index if not exists idx_courses_teacher      on public.courses(teacher_id);
create index if not exists idx_enrollments_student  on public.enrollments(student_id);
create index if not exists idx_lectures_course      on public.lectures(course_id);
create index if not exists idx_files_course         on public.files(course_id);
create index if not exists idx_files_lecture        on public.files(lecture_id);
create index if not exists idx_attendance_student   on public.attendance(student_id);
create index if not exists idx_questions_lecture    on public.questions(lecture_id);
create index if not exists idx_answers_student      on public.question_answers(student_id);
create index if not exists idx_exam_questions_exam  on public.exam_questions(exam_id);
create index if not exists idx_attempts_student     on public.exam_attempts(student_id);
create index if not exists idx_assignments_course   on public.assignments(course_id);
create index if not exists idx_submissions_student  on public.submissions(student_id);
create index if not exists idx_notifications_user   on public.notifications(user_id);
create index if not exists idx_ai_messages_user     on public.ai_messages(user_id);
create index if not exists idx_library_items_section on public.library_items(section_id);
create index if not exists idx_points_ledger_user   on public.points_ledger(user_id, course_id);
create index if not exists idx_archived_at          on public.archived_records(archived_at);

-- ---------- تفعيل RLS (الوصول عبر الخادم بمفتاح service_role فقط) ----------
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

