-- ============================================================
-- 0124_publication_review.sql — تفعيل التحكيم السري المزدوج للنشر العلمي
-- ============================================================
-- القواعد المُفعّلة من لحظة التطبيق، بلا تغيير في مضمونها:
--   • الباحث لا يعرف المحكّمين، والمحكّمون لا يعرفون الباحث.
--   • محكّمان مختلفان على الأقل، من ذوي الاختصاص والرتبة العلمية المناسبة.
--   • خمسة محاور من 10 لكل محكّم (المجموع 50) + توصية إلزامية.
--   • حد النشر: مجموع لا يقل عن 30 وتوصية متوسطها مقبول أو أعلى.
--   • مهلة البت ستة أشهر، ومهلة التعديل شهر واحد تُسجّل ولا تُهمَل.
--   • الأوراق تُرسل للمحكّم بلا أسماء أو عناوين أو مراجع تكشف الهوية.
--   • سرية التحكيم: لا تعود الملاحظات إلى الباحث ولا يعرف المحكّمين.
-- لا تُعاد حساب بيانات سابقة، ولا تُحذف صفوف نشر أو تحكيم قائمة.
-- لا يُطبَّق إلا بعد تأكيد منفصل من المالك.
--
-- ملاحظة توثيقية على التوقيع: تقترح الخطة دالة
-- reviewer_record_publication_decision(p_publication_id, p_decision, p_reason)
-- بثلاثة وسائط، لكن القاعدة الحاكمة تفرض خمسة محاور درجات وتوصية إلزامية
-- وملاحظات تحريرية. لذلك يُستخدم التوقيع الموسّع أدناه
-- (p_publication_id, p_scores, p_recommendation, p_notes)؛ التوقيع الأصلي
-- لا يستطيع استيعاب القاعدة كما هي. لا تغيير في مضمون القاعدة، بل في شكل
-- الاستدعاء فقط، وهذا موثّق هنا صراحةً.
--
-- إعادة العرض: التوصية «major» تعني «إعادة عرض للمحكّمين»؛ لذلك عند اكتمال
-- المراجعتين واستقرار الحالة revisions تُفتح جولة جديدة بالمحكّمين أنفسهم،
-- بمهلة بتّ ستة أشهر وبلا قرارات، مع نسخ الحزمة المخفية كما هي. الجولة السابقة
-- وقراراتها تبقى محفوظة كسجلّ تاريخي.
-- ============================================================

begin;

-- ---------------------------------------------------------------------------
-- 1) نسخة البحث المخفية الهوية: يرفض التعيين بدونها، ولا يُعدّل مسار البحث الأصلي.
-- ---------------------------------------------------------------------------
alter table public.publications add column if not exists anonymized_file text;

-- ---------------------------------------------------------------------------
-- 2) بيانات أهلية المحكّم: الاختصاص والرتبة يُسجّlan صراحةً ويقرّهما المالك.
-- ---------------------------------------------------------------------------
create table if not exists public.publication_reviewer_credentials (
  user_id        bigint primary key references public.users(id) on delete cascade,
  academic_rank  text not null check (btrim(academic_rank) <> ''),
  specialization text not null check (btrim(specialization) <> ''),
  verified_by    bigint not null references public.users(id) on delete restrict,
  verified_at    timestamptz not null default now()
);

alter table public.publication_reviewer_credentials enable row level security;
revoke all on public.publication_reviewer_credentials from public, anon, authenticated;
grant all on public.publication_reviewer_credentials to service_role;

-- ---------------------------------------------------------------------------
-- 3) التعيينات: صف لكل جولة تحكيم، مع الحزمة المخفية والمواعيد النهائية.
-- ---------------------------------------------------------------------------
create table if not exists public.publication_review_assignments (
  id                      bigint generated by default as identity primary key,
  publication_id          bigint not null references public.publications(id) on delete cascade,
  round                   integer not null default 1 check (round >= 1),
  reviewer1_id            bigint not null references public.users(id) on delete restrict,
  reviewer2_id            bigint not null references public.users(id) on delete restrict,
  reviewer1_rank          text not null,
  reviewer1_specialization text not null,
  reviewer2_rank          text not null,
  reviewer2_specialization text not null,
  assigned_by             bigint not null references public.users(id) on delete restrict,
  assigned_at             timestamptz not null default now(),
  decision_deadline_at    timestamptz not null,
  revision_deadline_at    timestamptz,
  anonymized_packet       jsonb not null,
  final_status            text,
  finalized_at            timestamptz,
  final_total_score       numeric(5,2),
  average_recommendation  numeric(4,2),
  check (reviewer1_id <> reviewer2_id),
  unique (publication_id, round)
);

create index if not exists publication_review_assignments_reviewer1_idx
  on public.publication_review_assignments (reviewer1_id, decision_deadline_at);
create index if not exists publication_review_assignments_reviewer2_idx
  on public.publication_review_assignments (reviewer2_id, decision_deadline_at);

alter table public.publication_review_assignments enable row level security;
revoke all on public.publication_review_assignments from public, anon, authenticated;
grant all on public.publication_review_assignments to service_role;

-- ---------------------------------------------------------------------------
-- 4) القرارات: صف واحد لكل محكّم لكل جولة، والملاحظات سرية لا تصل للباحث.
-- ---------------------------------------------------------------------------
create table if not exists public.publication_review_decisions (
  id             bigint generated by default as identity primary key,
  assignment_id  bigint not null references public.publication_review_assignments(id) on delete cascade,
  publication_id bigint not null references public.publications(id) on delete cascade,
  reviewer_id    bigint not null references public.users(id) on delete restrict,
  scores         jsonb not null check (jsonb_typeof(scores) = 'object'),
  total_score    numeric(5,2) not null check (total_score between 0 and 50),
  recommendation text not null check (recommendation in ('accept','minor','major','reject')),
  notes          text,
  decided_at     timestamptz not null default now(),
  unique (assignment_id, reviewer_id)
);

create index if not exists publication_review_decisions_assignment_idx
  on public.publication_review_decisions (assignment_id);

alter table public.publication_review_decisions enable row level security;
revoke all on public.publication_review_decisions from public, anon, authenticated;
grant all on public.publication_review_decisions to service_role;

-- ---------------------------------------------------------------------------
-- 5) سياسات القراءة: المالك فقط يرى التعيينات، والمحكّم يرى حزمة بلا هوية.
--    الباحث لا يقرأ assigned_reviewers ولا مراجعة ولا ملاحظات.
-- ---------------------------------------------------------------------------
drop policy if exists publications_select on public.publications;
create policy publications_select on public.publications
  for select to authenticated
  using (
    public.is_owner() or public.is_assistant()
  );

drop policy if exists publication_reviews_select on public.publication_reviews;
create policy publication_reviews_select on public.publication_reviews
  for select to authenticated
  using (
    public.is_owner() or public.is_assistant()
    or reviewer_id = public.current_user_id()
  );

revoke select on public.publications from authenticated;

create or replace view public.publications_author with (security_invoker = false) as select
  p.id, p.title, p.abstract_ar, p.abstract_en, p.keywords, p.status,
  p.published_at, p.created_at, p.updated_at
  from public.publications p
 where p.author_id = public.current_user_id();

revoke all on public.publications_author from public, anon;
grant select on public.publications_author to authenticated;

-- ---------------------------------------------------------------------------
-- 6) كتابة المالك: حفظ النسخة المخفية وتسجيل أهلية المحكّم.
-- ---------------------------------------------------------------------------
create or replace function public.management_set_publication_anonymized_file(
  p_publication_id bigint,
  p_file text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_file text := nullif(btrim(coalesce(p_file, '')), '');
begin
  if v_uid is null or not public.is_owner() then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  if p_publication_id is null then
    return jsonb_build_object('ok', false, 'error', 'publication_required');
  end if;
  if v_file is null then
    return jsonb_build_object('ok', false, 'error', 'anonymized_file_required');
  end if;

  update public.publications
     set anonymized_file = v_file, updated_at = now()
   where id = p_publication_id;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'publication_not_found');
  end if;

  insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
  values (
    v_uid, 'publication_anonymized_file_set', 'publications', p_publication_id,
    jsonb_build_object('file_recorded', true)
  );

  return jsonb_build_object('ok', true, 'data', jsonb_build_object('anonymized_file', v_file));
end;
$$;

create or replace function public.management_set_publication_reviewer_credentials(
  p_reviewer_id bigint,
  p_academic_rank text,
  p_specialization text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_rank text := nullif(btrim(coalesce(p_academic_rank, '')), '');
  v_specialization text := nullif(btrim(coalesce(p_specialization, '')), '');
  v_found boolean;
begin
  if v_uid is null or not public.is_owner() then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  if v_rank is null or v_specialization is null then
    return jsonb_build_object('ok', false, 'error', 'credentials_required');
  end if;

  select exists (
    select 1 from public.users u
     where u.id = p_reviewer_id and u.role = 'teacher' and u.is_active = true
  ) into v_found;
  if not v_found then
    return jsonb_build_object('ok', false, 'error', 'reviewer_not_eligible');
  end if;

  insert into public.publication_reviewer_credentials
    (user_id, academic_rank, specialization, verified_by, verified_at)
  values (p_reviewer_id, v_rank, v_specialization, v_uid, now())
  on conflict (user_id) do update
     set academic_rank = excluded.academic_rank,
         specialization = excluded.specialization,
         verified_by = excluded.verified_by,
         verified_at = excluded.verified_at;

  insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
  values (
    v_uid, 'publication_reviewer_credentials_set', 'users', p_reviewer_id,
    jsonb_build_object('academic_rank', v_rank, 'specialization', v_specialization)
  );

  return jsonb_build_object('ok', true, 'data', jsonb_build_object('reviewer_id', p_reviewer_id));
end;
$$;

-- ---------------------------------------------------------------------------
-- 7) تعيين المحكّمين: مالك فقط، اثنان مختلفان، ليسا الباحث، أهليّة موثّقة،
--    وحزمة بلا أسماء أو عناوين أو مراجع تكشف الهوية، ومهلة ستة أشهر.
-- ---------------------------------------------------------------------------
create or replace function public.management_assign_publication_reviewers(
  p_publication_id bigint,
  p_reviewer1 bigint,
  p_reviewer2 bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_author_id bigint;
  v_title text;
  v_abstract_ar text;
  v_abstract_en text;
  v_anonymized_file text;
  v_author_name text;
  v_author_email text;
  v_author_phone text;
  v_author_university_id text;
  v_author_name_key text;
  v_author_email_key text;
  v_author_phone_key text;
  v_author_university_key text;
  v_title_clean text;
  v_abstract_ar_clean text;
  v_abstract_en_clean text;
  v_rank1 text;
  v_specialization1 text;
  v_rank2 text;
  v_specialization2 text;
  v_round integer;
  v_packet jsonb;
  v_assignment_id bigint;
  v_deadline timestamptz;
begin
  if v_uid is null or not public.is_owner() then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  if p_publication_id is null then
    return jsonb_build_object('ok', false, 'error', 'publication_required');
  end if;
  if p_reviewer1 is null or p_reviewer2 is null then
    return jsonb_build_object('ok', false, 'error', 'reviewers_required');
  end if;
  if p_reviewer1 = p_reviewer2 then
    return jsonb_build_object('ok', false, 'error', 'distinct_reviewers_required');
  end if;

  perform pg_advisory_xact_lock(hashtext(p_publication_id::text));

  select p.author_id, p.title, p.abstract_ar, p.abstract_en, p.anonymized_file
    into v_author_id, v_title, v_abstract_ar, v_abstract_en, v_anonymized_file
    from public.publications p
   where p.id = p_publication_id;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'publication_not_found');
  end if;
  if p_reviewer1 = v_author_id or p_reviewer2 = v_author_id then
    return jsonb_build_object('ok', false, 'error', 'reviewer_cannot_be_author');
  end if;
  if v_anonymized_file is null or btrim(v_anonymized_file) = '' then
    return jsonb_build_object('ok', false, 'error', 'anonymized_file_required');
  end if;

  select u.name, u.email, u.phone, u.university_id
    into v_author_name, v_author_email, v_author_phone, v_author_university_id
    from public.users u
   where u.id = v_author_id;

  select c.academic_rank, c.specialization
    into v_rank1, v_specialization1
    from public.publication_reviewer_credentials c
   where c.user_id = p_reviewer1;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'reviewer_credentials_required');
  end if;

  select c.academic_rank, c.specialization
    into v_rank2, v_specialization2
    from public.publication_reviewer_credentials c
   where c.user_id = p_reviewer2;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'reviewer_credentials_required');
  end if;

  if not exists (
    select 1 from public.users u
     where u.id = p_reviewer1 and u.role = 'teacher' and u.is_active = true
  ) or not exists (
    select 1 from public.users u
     where u.id = p_reviewer2 and u.role = 'teacher' and u.is_active = true
  ) then
    return jsonb_build_object('ok', false, 'error', 'reviewer_not_eligible');
  end if;

  -- مفاتيح غير فارغة حتى لا يُدخل replace() نصاً في موضع كل حرف.
  v_author_name_key := coalesce(nullif(btrim(coalesce(v_author_name, '')), ''), chr(1));
  v_author_email_key := coalesce(nullif(btrim(coalesce(v_author_email, '')), ''), chr(1));
  v_author_phone_key := coalesce(nullif(btrim(coalesce(v_author_phone, '')), ''), chr(1));
  v_author_university_key := coalesce(nullif(btrim(coalesce(v_author_university_id, '')), ''), chr(1));

  -- إزالة الاسم والبريد والهاتف والجامعة، ثم إزالة إحالات [n] واقتباسات السنة.
  v_title_clean := regexp_replace(
    replace(replace(replace(replace(coalesce(v_title, ''),
      v_author_name_key, ''), v_author_email_key, ''), v_author_phone_key, ''), v_author_university_key, ''),
    '\[[0-9]+\]|\([^)]*(19|20)[0-9]{2}[^)]*\)', '', 'g');
  v_abstract_ar_clean := regexp_replace(
    replace(replace(replace(replace(coalesce(v_abstract_ar, ''),
      v_author_name_key, ''), v_author_email_key, ''), v_author_phone_key, ''), v_author_university_key, ''),
    '\[[0-9]+\]|\([^)]*(19|20)[0-9]{2}[^)]*\)', '', 'g');
  v_abstract_en_clean := regexp_replace(
    replace(replace(replace(replace(coalesce(v_abstract_en, ''),
      v_author_name_key, ''), v_author_email_key, ''), v_author_phone_key, ''), v_author_university_key, ''),
    '\[[0-9]+\]|\([^)]*(19|20)[0-9]{2}[^)]*\)', '', 'g');

  select coalesce(max(a.round), 0) + 1
    into v_round
    from public.publication_review_assignments a
   where a.publication_id = p_publication_id;

  v_deadline := now() + interval '6 months';

  -- خمسة محاور التقييم: 'originality', 'methodology', 'documentation', 'analysis', 'writing'
  v_packet := jsonb_build_object(
    'title', v_title_clean,
    'abstract_ar', v_abstract_ar_clean,
    'abstract_en', v_abstract_en_clean,
    'file', btrim(v_anonymized_file),
    'axes', jsonb_build_array('originality','methodology','documentation','analysis','writing')
  );

  insert into public.publication_review_assignments (
    publication_id, round, reviewer1_id, reviewer2_id,
    reviewer1_rank, reviewer1_specialization, reviewer2_rank, reviewer2_specialization,
    assigned_by, assigned_at, decision_deadline_at, anonymized_packet
  )
  values (
    p_publication_id, v_round, p_reviewer1, p_reviewer2,
    v_rank1, v_specialization1, v_rank2, v_specialization2,
    v_uid, now(), v_deadline, v_packet
  )
  returning id into v_assignment_id;

  update public.publications
     set status = 'under_review', updated_at = now()
   where id = p_publication_id;

  insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
  values (
    v_uid, 'publication_reviewers_assigned', 'publications', p_publication_id,
    jsonb_build_object(
      'assignment_id', v_assignment_id, 'round', v_round,
      'reviewer1_rank', v_rank1, 'reviewer2_rank', v_rank2,
      'decision_deadline_months', 6, 'anonymized', true
    )
  );

  return jsonb_build_object(
    'ok', true,
    'data', jsonb_build_object(
      'assignment_id', v_assignment_id,
      'round', v_round,
      'decision_deadline_at', v_deadline
    )
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- 8) طابور المالك وقائمة المحكّمين: بيانات إدارية لا تُعرض للباحث أو للمحكّم.
-- ---------------------------------------------------------------------------
create or replace function public.management_publication_review_queue()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_data jsonb;
begin
  if v_uid is null or not public.is_owner() then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', q.id,
           'title', q.title,
           'status', q.status,
           'anonymized_file', q.anonymized_file,
           'round', q.round,
           'assigned_at', q.assigned_at,
           'decision_deadline_at', q.decision_deadline_at,
           'revision_deadline_at', q.revision_deadline_at,
           'final_status', q.final_status
         ) order by q.id desc), '[]'::jsonb)
    into v_data
    from (
      select p.id, p.title, p.status, p.anonymized_file,
             a.round, a.assigned_at, a.decision_deadline_at,
             a.revision_deadline_at, a.final_status
        from public.publications p
        left join lateral (
          select x.round, x.assigned_at, x.decision_deadline_at,
                 x.revision_deadline_at, x.final_status
            from public.publication_review_assignments x
           where x.publication_id = p.id
           order by x.round desc
           limit 1
        ) a on true
    ) q;

  return jsonb_build_object('ok', true, 'data', v_data);
end;
$$;

create or replace function public.management_publication_reviewer_candidates()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_data jsonb;
begin
  if v_uid is null or not public.is_owner() then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', u.id,
           'name', u.name,
           'position', u.position,
           'academic_rank', c.academic_rank,
           'specialization', c.specialization
         ) order by u.id), '[]'::jsonb)
    into v_data
    from public.users u
    left join public.publication_reviewer_credentials c on c.user_id = u.id
   where u.role = 'teacher' and u.is_active = true;

  return jsonb_build_object('ok', true, 'data', v_data);
end;
$$;

-- ---------------------------------------------------------------------------
-- 9) حزمة المحكّم: لا تحتوي على هوية الباحث ولا على أسماء المحكّمين أو ملاحظات.
-- ---------------------------------------------------------------------------
create or replace function public.reviewer_publication_assignments()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_data jsonb;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not_authenticated');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'publication_id', a.publication_id,
           'round', a.round,
           'decision_deadline_at', a.decision_deadline_at,
           'decided', exists (
             select 1 from public.publication_review_decisions d
              where d.assignment_id = a.id and d.reviewer_id = v_uid
           )
         ) order by a.decision_deadline_at), '[]'::jsonb)
    into v_data
    from public.publication_review_assignments a
   where a.round = (
            select max(x.round)
              from public.publication_review_assignments x
             where x.publication_id = a.publication_id
          )
     and (a.reviewer1_id = v_uid or a.reviewer2_id = v_uid);

  return jsonb_build_object('ok', true, 'data', v_data);
end;
$$;

create or replace function public.reviewer_publication_blob(p_publication_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_packet jsonb;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not_authenticated');
  end if;

  select a.anonymized_packet
    into v_packet
    from public.publication_review_assignments a
   where a.publication_id = p_publication_id
     and a.round = (
       select max(x.round)
         from public.publication_review_assignments x
        where x.publication_id = p_publication_id
     )
     and (v_uid = a.reviewer1_id or v_uid = a.reviewer2_id)
   limit 1;

  if v_packet is null then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;

  return jsonb_build_object('ok', true, 'data', jsonb_build_object(
    'title', v_packet -> 'title',
    'abstract_ar', v_packet -> 'abstract_ar',
    'abstract_en', v_packet -> 'abstract_en',
    'file', v_packet -> 'file',
    'axes', v_packet -> 'axes'
  ));
end;
$$;

-- ---------------------------------------------------------------------------
-- 10) قرار المحكّم: خمسة محاور 0..10، توصية إلزامية، صف واحد لكل محكّم،
--     والقرار النهائي لا يُحتسب إلا بعد المراجعتين وعند تحقق الحدّين.
-- ---------------------------------------------------------------------------
create or replace function public.reviewer_record_publication_decision(
  p_publication_id bigint,
  p_scores jsonb,
  p_recommendation text,
  p_notes text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.current_user_id();
  v_axes text[] := array['originality','methodology','documentation','analysis','writing'];
  v_axis text;
  v_score numeric;
  v_total numeric := 0;
  v_recommendation text := lower(btrim(coalesce(p_recommendation, '')));
  v_assignment public.publication_review_assignments%rowtype;
  v_count integer;
  v_total1 numeric;
  v_total2 numeric;
  v_rank1 integer;
  v_rank2 integer;
  v_rank integer;
  v_final text;
  v_revision_deadline timestamptz;
  v_next_round integer;
  v_rereview_deadline timestamptz;
  v_next_assignment_id bigint;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not_authenticated');
  end if;

  select a.* into v_assignment
    from public.publication_review_assignments a
   where a.publication_id = p_publication_id
     and a.round = (
       select max(x.round)
         from public.publication_review_assignments x
        where x.publication_id = p_publication_id
     )
     and (v_uid = a.reviewer1_id or v_uid = a.reviewer2_id)
   limit 1;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;

  if exists (
      select 1 from public.publication_review_decisions d
       where d.assignment_id = v_assignment.id and d.reviewer_id = v_uid
  ) then
    return jsonb_build_object('ok', false, 'error', 'duplicate_decision');
  end if;

  if p_publication_id is null or jsonb_typeof(p_scores) <> 'object' then
    return jsonb_build_object('ok', false, 'error', 'invalid_scores');
  end if;
  if (select count(*) from jsonb_object_keys(p_scores)) <> 5 then
    return jsonb_build_object('ok', false, 'error', 'invalid_scores');
  end if;

  foreach v_axis in array v_axes loop
    if not (p_scores ? v_axis) or jsonb_typeof(p_scores -> v_axis) <> 'number' then
      return jsonb_build_object('ok', false, 'error', 'invalid_scores');
    end if;
    v_score := (p_scores ->> v_axis)::numeric;
    if v_score < 0 or v_score > 10 then
      return jsonb_build_object('ok', false, 'error', 'invalid_scores');
    end if;
    v_total := v_total + v_score;
  end loop;

  if v_recommendation not in ('accept','minor','major','reject') then
    return jsonb_build_object('ok', false, 'error', 'invalid_recommendation');
  end if;
  v_rank := case v_recommendation
              when 'accept' then 3
              when 'minor' then 2
              when 'major' then 1
              else 0
            end;

  insert into public.publication_review_decisions (
    assignment_id, publication_id, reviewer_id, scores, total_score, recommendation, notes
  )
  values (
    v_assignment.id, p_publication_id, v_uid, p_scores, v_total, v_recommendation, p_notes
  );

  insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
  values (
    v_uid, 'publication_review_decision_recorded', 'publications', p_publication_id,
    jsonb_build_object('assignment_id', v_assignment.id, 'total_score', v_total, 'recommendation', v_recommendation)
  );

  select count(*),
         max(case when d.reviewer_id = v_assignment.reviewer1_id then d.total_score end),
         max(case when d.reviewer_id = v_assignment.reviewer2_id then d.total_score end),
         max(case when d.reviewer_id = v_assignment.reviewer1_id then
           case d.recommendation when 'accept' then 3 when 'minor' then 2 when 'major' then 1 else 0 end end),
         max(case when d.reviewer_id = v_assignment.reviewer2_id then
           case d.recommendation when 'accept' then 3 when 'minor' then 2 when 'major' then 1 else 0 end end)
    into v_count, v_total1, v_total2, v_rank1, v_rank2
    from public.publication_review_decisions d
   where d.assignment_id = v_assignment.id;

  if v_count < 2 then
    return jsonb_build_object('ok', true, 'final', false, 'data', jsonb_build_object('recorded', true));
  end if;

  if least(v_total1, v_total2) >= 30 then
    if v_rank1 = 0 or v_rank2 = 0 then
      v_final := 'rejected';
    elsif v_rank1 = 1 or v_rank2 = 1 then
      v_final := 'revisions';
      v_revision_deadline := now() + interval '1 month';
    elsif (v_rank1 + v_rank2) / 2.0 >= 2 then
      v_final := 'accepted';
    else
      v_final := 'rejected';
    end if;
  else
    v_final := 'rejected';
  end if;

  update public.publication_review_assignments
     set final_status = v_final,
         finalized_at = now(),
         final_total_score = least(v_total1, v_total2),
         average_recommendation = (v_rank1 + v_rank2) / 2.0,
         revision_deadline_at = case
           when v_final = 'revisions' then v_revision_deadline
           else revision_deadline_at
         end
   where id = v_assignment.id;

  update public.publications
     set status = v_final, updated_at = now()
   where id = p_publication_id;

  insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
  values (
    v_uid, 'publication_review_finalized', 'publications', p_publication_id,
    jsonb_build_object(
      'assignment_id', v_assignment.id, 'status', v_final,
      'min_total_score', least(v_total1, v_total2),
      'average_recommendation', (v_rank1 + v_rank2) / 2.0,
      'revision_deadline_at', v_revision_deadline
    )
  );

  -- إعادة عرض للمحكّمين: الجولة الجديدة تستخدم المحكّمين نفسيهم والحزمة المخفية
  -- نفسها، من دون نقل أي قرار أو هوية للباحث؛ الجولة السابقة تبقى للتاريخ.
  if v_final = 'revisions' then
    v_next_round := coalesce((
      select max(x.round)
        from public.publication_review_assignments x
       where x.publication_id = p_publication_id
    ), v_assignment.round) + 1;
    v_rereview_deadline := now() + interval '6 months';

    insert into public.publication_review_assignments (
      publication_id, round, reviewer1_id, reviewer2_id,
      reviewer1_rank, reviewer1_specialization, reviewer2_rank, reviewer2_specialization,
      assigned_by, assigned_at, decision_deadline_at, anonymized_packet
    )
    select
      v_assignment.publication_id, v_next_round,
      v_assignment.reviewer1_id, v_assignment.reviewer2_id,
      v_assignment.reviewer1_rank, v_assignment.reviewer1_specialization,
      v_assignment.reviewer2_rank, v_assignment.reviewer2_specialization,
      v_assignment.assigned_by, now(), v_rereview_deadline,
      v_assignment.anonymized_packet
    returning id into v_next_assignment_id;

    insert into public.audit_logs (actor_id, action, table_name, record_id, new_data)
    values (
      v_uid, 'publication_rereview_round_opened', 'publications', p_publication_id,
      jsonb_build_object(
        'previous_assignment_id', v_assignment.id,
        'assignment_id', v_next_assignment_id,
        'round', v_next_round,
        'reviewers_unchanged', true,
        'decision_deadline_months', 6,
        'anonymized', true
      )
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'final', true,
    'data', jsonb_build_object('status', v_final, 'revision_deadline_at', v_revision_deadline)
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- 11) الصلاحيات: التنفيذ للمستخدمين المصادق عليهم وللخلفية فقط، بلا anon.
-- ---------------------------------------------------------------------------
do $$
declare
  v_fn text;
  v_fns text[] := array[
    'management_assign_publication_reviewers(bigint,bigint,bigint)',
    'management_set_publication_anonymized_file(bigint,text)',
    'management_set_publication_reviewer_credentials(bigint,text,text)',
    'management_publication_review_queue()',
    'management_publication_reviewer_candidates()',
    'reviewer_publication_blob(bigint)',
    'reviewer_publication_assignments()',
    'reviewer_record_publication_decision(bigint,jsonb,text,text)'
  ];
begin
  foreach v_fn in array v_fns loop
    execute format('revoke all on function public.%s from public, anon', v_fn);
    execute format('grant execute on function public.%s to authenticated, service_role', v_fn);
  end loop;
end
$$;

notify pgrst, 'reload schema';

commit;
